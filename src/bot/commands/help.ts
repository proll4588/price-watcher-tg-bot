import { Context } from "telegraf";
import { botLogger } from "../../utils/logger";

export async function helpCommand(ctx: Context): Promise<void> {
  try {
    const helpMessage =
      `📚 Справка по командам Price Watcher\n\n` +
      `🎯 Основные команды:\n` +
      `/start - Запуск бота и основная информация\n` +
      `/add <ссылка> - Добавить товар для отслеживания\n` +
      `/list - Список отслеживаемых товаров\n` +
      `/remove <ID> - Удалить товар из отслеживания\n` +
      `/settings - Настройки отслеживания\n` +
      `/pro - Информация о Pro-подписке\n` +
      `/help - Эта справка\n\n` +
      `🔗 Поддерживаемые маркетплейсы:\n` +
      `• Wildberries (wildberries.ru, wildberries.com)\n` +
      `• Яндекс.Маркет (market.yandex.ru) - скоро\n\n` +
      `⚙️ Как использовать:\n` +
      `1. Отправьте ссылку на товар\n` +
      `2. Бот автоматически добавит товар в отслеживание\n` +
      `3. Получайте уведомления при изменении цены\n\n` +
      `💰 Тарифы:\n` +
      `🆓 Бесплатный:\n` +
      `• До 3 товаров\n` +
      `• Проверка каждые 6 часов\n` +
      `• Базовые уведомления\n\n` +
      `⭐️ Pro (99₽/мес):\n` +
      `• До 50 товаров\n` +
      `• Проверка каждые 2 часа\n` +
      `• Расширенные фильтры\n` +
      `• Приоритетная поддержка\n\n` +
      `🔍 Фильтры цен:\n` +
      `• Минимальная цена\n` +
      `• Максимальная цена\n` +
      `• Процент скидки\n\n` +
      `📞 Поддержка:\n` +
      `Если у вас есть вопросы, обратитесь к @support_username`;

    await ctx.reply(helpMessage);

    botLogger.info("Пользователь запросил справку", {
      userId: (ctx as any).user?.id,
    });
  } catch (error) {
    botLogger.error("Ошибка в команде help:", { error });
    await ctx.reply("❌ Произошла ошибка при отображении справки.");
  }
}
